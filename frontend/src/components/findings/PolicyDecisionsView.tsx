import React from 'react';
import { Card, CardHeader, CardTitle, CardDescription, CardContent } from '../ui/Card';
import { Table, TableHeader, TableBody, TableRow, TableHead, TableCell } from '../ui/Table';
import { Badge } from '../ui/Badge';
import { Button } from '../ui/Button';
import { Alert } from '../ui/Alert';
import { DecisionResultItem, DecisionRun } from '../../types/policy';
import { HumanReviewCase } from '../../types/review';
import { useAuth } from '../../context/AuthContext';
import {
  Sliders,
  CheckCircle2,
  XCircle,
  Clock,
  RefreshCw,
  UserCheck,
} from 'lucide-react';

interface PolicyDecisionsViewProps {
  decisionRun: DecisionRun | null;
  decisions: DecisionResultItem[];
  reviewCases: HumanReviewCase[];
  isEvaluating: boolean;
  onTriggerEvaluation: () => void;
  onOpenReviewModal: (caseId?: string) => void;
}

export const PolicyDecisionsView: React.FC<PolicyDecisionsViewProps> = ({
  decisionRun,
  decisions,
  reviewCases,
  isEvaluating,
  onTriggerEvaluation,
  onOpenReviewModal,
}) => {
  const { hasPermission } = useAuth();

  const summary = decisionRun?.decisionsSummary || {
    totalEvaluated: decisions.length,
    redactCount: decisions.filter((d) => d.decision === 'REDACT').length,
    keepCount: decisions.filter((d) => d.decision === 'KEEP').length,
    reviewCount: decisions.filter((d) => d.decision === 'REVIEW').length,
  };

  const hasUnresolvedReviews = summary.reviewCount > 0;

  return (
    <div className="space-y-6">
      {/* Policy Summary Metrics */}
      <div className="grid grid-cols-1 sm:grid-cols-4 gap-4">
        <div className="p-4 rounded-lg bg-surface-white border border-surface-border shadow-subtle">
          <div className="flex items-center justify-between text-xs text-text-secondary">
            <span>Total Evaluated</span>
            <Sliders className="w-4 h-4 text-brand-teal" />
          </div>
          <p className="mt-2 text-2xl font-bold text-brand-deep-teal tabular-nums">
            {summary.totalEvaluated}
          </p>
          <span className="text-[11px] text-text-muted">Total policy candidates</span>
        </div>

        <div className="p-4 rounded-lg bg-surface-white border border-surface-border shadow-subtle">
          <div className="flex items-center justify-between text-xs text-text-secondary">
            <span>Mandatory Redactions</span>
            <XCircle className="w-4 h-4 text-status-critical" />
          </div>
          <p className="mt-2 text-2xl font-bold text-status-critical tabular-nums">
            {summary.redactCount}
          </p>
          <span className="text-[11px] text-text-muted">High-confidence PII</span>
        </div>

        <div className="p-4 rounded-lg bg-surface-white border border-surface-border shadow-subtle">
          <div className="flex items-center justify-between text-xs text-text-secondary">
            <span>Preserved (Keep)</span>
            <CheckCircle2 className="w-4 h-4 text-status-success" />
          </div>
          <p className="mt-2 text-2xl font-bold text-status-success tabular-nums">
            {summary.keepCount}
          </p>
          <span className="text-[11px] text-text-muted">Whitelisted / Public context</span>
        </div>

        <div className="p-4 rounded-lg bg-surface-white border border-surface-border shadow-subtle">
          <div className="flex items-center justify-between text-xs text-text-secondary">
            <span>Pending Review</span>
            <Clock className="w-4 h-4 text-status-warning" />
          </div>
          <p className="mt-2 text-2xl font-bold text-status-warning tabular-nums">
            {summary.reviewCount}
          </p>
          <span className="text-[11px] text-text-muted">Requires human adjudication</span>
        </div>
      </div>

      {/* Unresolved Review Invariant Alert */}
      {hasUnresolvedReviews && (
        <Alert
          variant="warning"
          title="Unresolved Policy Decisions Detected"
          className="border-status-warning"
        >
          This document contains <strong>{summary.reviewCount} finding(s)</strong> evaluated as{' '}
          <code>REVIEW</code>. Under tenant policy invariants, documents with unresolved review
          decisions cannot be automatically certified for sanitized release until human
          adjudication is recorded.
        </Alert>
      )}

      {/* Decisions Table Card */}
      <Card>
        <CardHeader>
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
            <div>
              <CardTitle>Evaluated Policy Recommendations</CardTitle>
              <CardDescription>
                Decisions generated by deterministic and regex policy engine rules.
              </CardDescription>
            </div>
            <div className="flex items-center gap-2">
              {hasPermission('REVIEW_EXECUTE') && reviewCases.length > 0 && (
                <Button
                  variant="outline"
                  size="sm"
                  onClick={() => onOpenReviewModal(reviewCases[0]?.reviewCaseId)}
                  leftIcon={<UserCheck className="w-3.5 h-3.5" />}
                >
                  Adjudicate Review ({reviewCases.length})
                </Button>
              )}
              {hasPermission('DECISION_EXECUTE') && (
                <Button
                  variant="primary"
                  size="sm"
                  onClick={onTriggerEvaluation}
                  isLoading={isEvaluating}
                  leftIcon={<RefreshCw className="w-3.5 h-3.5" />}
                >
                  Run Policy Evaluation
                </Button>
              )}
            </div>
          </div>
        </CardHeader>

        <CardContent>
          {decisions.length === 0 ? (
            <div className="p-8 text-center border-2 border-dashed border-surface-border rounded-lg bg-surface-cool/30">
              <Sliders className="w-8 h-8 text-text-muted mx-auto mb-2" />
              <p className="text-sm font-semibold text-text-primary">
                No policy decisions evaluated yet
              </p>
              <p className="text-xs text-text-secondary mt-1 max-w-md mx-auto">
                Execute policy evaluation to apply organizational rules and generate KEEP,
                REVIEW, and REDACT recommendations.
              </p>
            </div>
          ) : (
            <div className="overflow-x-auto">
              <Table>
                <TableHeader>
                  <TableRow>
                    <TableHead>Candidate ID</TableHead>
                    <TableHead>Decision</TableHead>
                    <TableHead>Decision Score</TableHead>
                    <TableHead>Matched Rule IDs</TableHead>
                    <TableHead>Rationale Codes</TableHead>
                    <TableHead>Evaluator Version</TableHead>
                  </TableRow>
                </TableHeader>
                <TableBody>
                  {decisions.map((d) => (
                    <TableRow key={d.decisionResultId || d.candidateId}>
                      <TableCell className="font-mono text-xs font-semibold text-brand-deep-teal">
                        {d.candidateId}
                      </TableCell>
                      <TableCell>
                        {d.decision === 'REDACT' ? (
                          <Badge variant="critical">REDACT</Badge>
                        ) : d.decision === 'REVIEW' ? (
                          <Badge variant="warning">REVIEW</Badge>
                        ) : (
                          <Badge variant="success">KEEP</Badge>
                        )}
                      </TableCell>
                      <TableCell className="tabular-nums text-xs font-medium">
                        {(d.decisionScore * 100).toFixed(1)}%
                      </TableCell>
                      <TableCell className="font-mono text-[11px] text-text-secondary">
                        {d.matchedRuleIds && d.matchedRuleIds.length > 0
                          ? d.matchedRuleIds.join(', ')
                          : 'DEFAULT_FALLBACK'}
                      </TableCell>
                      <TableCell className="font-mono text-[11px] text-text-secondary">
                        {d.rationaleCodes && d.rationaleCodes.length > 0
                          ? d.rationaleCodes.join(', ')
                          : 'NONE'}
                      </TableCell>
                      <TableCell className="text-xs text-text-muted">
                        v{d.evaluatorVersion || '1.0.0'}
                      </TableCell>
                    </TableRow>
                  ))}
                </TableBody>
              </Table>
            </div>
          )}
        </CardContent>
      </Card>
    </div>
  );
};
